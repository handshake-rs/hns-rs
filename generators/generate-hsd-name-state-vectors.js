#!/usr/bin/env node
'use strict';

const assert = require('node:assert');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const HSD_REVISION = '698e252ebc7b5c1dd0a9587e342fdd153d020ae4';
const HSD_VERSION = '8.99.0';
const SOURCE_HASHES = new Map([
  ['lib/covenants/namestate.js',
    '801ed6e763cc9131290e9973892059b06580055758d62e44bb5db7841c0eaac0'],
  ['lib/dns/resource.js',
    '95a9913c0e54465172791758a4885c9a9cb7ac45f16282328a4d73e736bc077f'],
  ['../bns/lib/encoding.js',
    '4813d00f5b1c64bad2dc87180fc2ace568d70c77010b1b647737a8a072243d6b']
]);

const mode = process.argv[2] || '--print';
const hsdRoot = path.resolve(
  process.argv[3] || process.env.HSD_ROOT || '../hsd'
);
const repositoryRoot = path.resolve(__dirname, '..');
const fixturePath = path.join(
  repositoryRoot,
  'fixtures',
  'hsd',
  'name-state-resource-v1.txt'
);

function sha256(bytes) {
  return crypto.createHash('sha256').update(bytes).digest('hex');
}

function verifyOracle() {
  const packageJSON = JSON.parse(
    fs.readFileSync(path.join(hsdRoot, 'package.json'), 'utf8')
  );
  assert.strictEqual(packageJSON.name, 'hsd');
  assert.strictEqual(packageJSON.version, HSD_VERSION);
  for (const [relative, expected] of SOURCE_HASHES) {
    const source = oracleSource(relative);
    assert.strictEqual(sha256(fs.readFileSync(source)), expected, source);
  }
}

function nameHash(name) {
  return crypto.createHash('sha3-256').update(name).digest();
}

function oracleSource(relative) {
  if (relative !== '../bns/lib/encoding.js')
    return path.resolve(hsdRoot, relative);
  const candidates = [
    path.resolve(hsdRoot, relative),
    path.join(hsdRoot, 'node_modules', 'bns', 'lib', 'encoding.js')
  ];
  const source = candidates.find((candidate) => fs.existsSync(candidate));
  assert(source, 'could not locate the installed BNS encoding source');
  return source;
}

function makeResource(Resource) {
  return new Resource().fromJSON({
    records: [
      {
        type: 'DS',
        keyTag: 4660,
        algorithm: 13,
        digestType: 2,
        digest: '00112233445566778899aabbccddeeff'
      },
      {type: 'NS', ns: 'ns1.example.'},
      {type: 'GLUE4', ns: 'ns1.example.', address: '192.0.2.1'},
      {type: 'GLUE6', ns: 'ns2.example.', address: '2001:db8::53'},
      {type: 'SYNTH4', address: '198.51.100.7'},
      {type: 'SYNTH6', address: '2001:db8::7'},
      {type: 'TXT', txt: ['wallet', 'proof']}
    ]
  });
}

function makeNameStates(NameState, Outpoint, resourceRaw) {
  const minimal = new NameState();
  minimal.name = Buffer.from('alpha', 'ascii');
  minimal.nameHash = nameHash(minimal.name);
  minimal.height = 100;
  minimal.renewal = 100;

  const populated = new NameState();
  populated.name = Buffer.from('handshake', 'ascii');
  populated.nameHash = nameHash(populated.name);
  populated.height = 0x10203040;
  populated.renewal = 0x50607080;
  populated.owner = new Outpoint(
    Buffer.from(Array.from({ length: 32 }, (_, index) => index)),
    70000
  );
  populated.value = 123456789;
  populated.highest = 987654321;
  populated.data = resourceRaw;
  populated.transfer = 1234;
  populated.revoked = 5678;
  populated.claimed = 9012;
  populated.renewals = 300;
  populated.registered = true;
  populated.expired = true;
  populated.weak = true;

  return {minimal, populated};
}

function render() {
  verifyOracle();
  const NameState = require(path.join(hsdRoot, 'lib/covenants/namestate'));
  const Outpoint = require(path.join(hsdRoot, 'lib/primitives/outpoint'));
  const {Resource} = require(path.join(hsdRoot, 'lib/dns/resource'));

  const resource = makeResource(Resource);
  const resourceRaw = resource.encode();
  assert(resourceRaw.equals(Resource.decode(resourceRaw).encode()));
  const {minimal, populated} = makeNameStates(NameState, Outpoint, resourceRaw);
  const minimalRaw = minimal.encode();
  const populatedRaw = populated.encode();
  assert(minimalRaw.equals(NameState.decode(minimalRaw).encode()));
  assert(populatedRaw.equals(NameState.decode(populatedRaw).encode()));
  assert.strictEqual(NameState.MAX_SIZE, 668);

  const lines = [
    '# hns-rs exact HSD NameState/resource vectors v1',
    '# Generated by generators/generate-hsd-name-state-vectors.js; do not edit.',
    `# hsd_revision=${HSD_REVISION}`,
    `# hsd_version=${HSD_VERSION}`,
    `# namestate_source_sha256=${SOURCE_HASHES.get('lib/covenants/namestate.js')}`,
    `# resource_source_sha256=${SOURCE_HASHES.get('lib/dns/resource.js')}`,
    `# bns_encoding_source_sha256=${SOURCE_HASHES.get('../bns/lib/encoding.js')}`,
    `resource_all_records=${resourceRaw.toString('hex')}`,
    `name_state_minimal_key=${minimal.nameHash.toString('hex')}`,
    `name_state_minimal=${minimalRaw.toString('hex')}`,
    `name_state_populated_key=${populated.nameHash.toString('hex')}`,
    `name_state_populated=${populatedRaw.toString('hex')}`
  ];
  return Buffer.from(`${lines.join('\n')}\n`, 'ascii');
}

function sidecar(content) {
  return `${sha256(content)}  ${path.basename(fixturePath)}\n`;
}

const content = render();
switch (mode) {
  case '--write':
    fs.mkdirSync(path.dirname(fixturePath), {recursive: true});
    fs.writeFileSync(fixturePath, content);
    fs.writeFileSync(`${fixturePath}.sha256`, sidecar(content), 'ascii');
    break;
  case '--check':
    assert(fs.readFileSync(fixturePath).equals(content), 'fixture differs');
    assert.strictEqual(
      fs.readFileSync(`${fixturePath}.sha256`, 'ascii'),
      sidecar(content),
      'fixture sidecar differs'
    );
    break;
  case '--print':
    process.stdout.write(content);
    break;
  default:
    throw new Error('usage: generate-hsd-name-state-vectors.js [--write|--check] [hsd-root]');
}
