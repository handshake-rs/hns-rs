#!/usr/bin/env node
'use strict';

const assert = require('node:assert');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const HSD_REVISION = '698e252ebc7b5c1dd0a9587e342fdd153d020ae4';
const HSD_VERSION = '8.99.0';
const SOURCE_HASHES = new Map([
  ['lib/protocol/policy.js',
    '1d8840bc6b8b6b4c78fa2e73337f3665b5b65329d650c44589b4a8a67a44a60e'],
  ['lib/primitives/tx.js',
    '7681f599330cba3ff72529da899ed309daa628f3efd500c5d04ba89dd5be9300'],
  ['lib/protocol/consensus.js',
    '9342ee033ca27fe1539b6047fbd3529bb912ae2cdbe456adf7828798fb5cc8a2']
]);
const VECTORS = [
  [0, 0, 1000],
  [1, 0, 0],
  [1, 0, 1],
  [1, 0, 500],
  [1, 0, 1000],
  [8, 0, 500],
  [3996, 0, 1],
  [3996, 0, 1000],
  [4000, 0, 1],
  [4000, 0, 1000],
  [4001, 0, 1000],
  [7996, 0, 1],
  [8000, 0, 1],
  [49380, 0, 4321],
  [1, 1, 1000],
  [100, 1, 1000],
  [320, 16, 1000],
  [321, 16, 1000],
  [300000, 16000, 1000],
  [400000, 16000, 0xffffffff],
  [4000000, 80000, 1000]
];

const mode = process.argv[2] || '--print';
const hsdRoot = path.resolve(
  process.argv[3] || process.env.HSD_ROOT || '../hsd'
);
const repositoryRoot = path.resolve(__dirname, '..');
const fixturePath = path.join(
  repositoryRoot,
  'fixtures',
  'hsd',
  'fee-policy-v1.txt'
);

function sha256(bytes) {
  return crypto.createHash('sha256').update(bytes).digest('hex');
}

function verifyOracle() {
  const packageJSON = JSON.parse(
    fs.readFileSync(path.join(hsdRoot, 'package.json'), 'utf8')
  );
  assert.strictEqual(packageJSON.name, 'hsd');
  assert.strictEqual(packageJSON.version, HSD_VERSION);
  for (const [relative, expected] of SOURCE_HASHES) {
    const source = path.join(hsdRoot, relative);
    assert.strictEqual(sha256(fs.readFileSync(source)), expected, source);
  }
}

function render() {
  verifyOracle();
  const policy = require(path.join(hsdRoot, 'lib/protocol/policy'));
  const TX = require(path.join(hsdRoot, 'lib/primitives/tx'));
  const consensus = require(path.join(hsdRoot, 'lib/protocol/consensus'));
  assert.strictEqual(consensus.WITNESS_SCALE_FACTOR, 4);
  assert.strictEqual(policy.BYTES_PER_SIGOP, 20);
  assert.strictEqual(policy.MIN_RELAY, 1000);

  const lines = [
    '# hns-rs exact HSD fee-policy vectors v1',
    '# Generated by generators/generate-hsd-fee-policy-vectors.js; do not edit.',
    `# hsd_revision=${HSD_REVISION}`,
    `# hsd_version=${HSD_VERSION}`,
    `# policy_source_sha256=${SOURCE_HASHES.get('lib/protocol/policy.js')}`,
    `# transaction_source_sha256=${SOURCE_HASHES.get('lib/primitives/tx.js')}`,
    `# consensus_source_sha256=${SOURCE_HASHES.get('lib/protocol/consensus.js')}`,
    '# fields=weight|sigops|policy_virtual_size|rate_per_1000_virtual_bytes|minimum_fee'
  ];
  for (const [weight, sigops, rate] of VECTORS) {
    const transaction = {getWeight: () => weight};
    const virtualSize = TX.prototype.getSigopsSize.call(transaction, sigops);
    const fee = policy.getMinFee(virtualSize, rate);
    assert(Number.isSafeInteger(virtualSize) && virtualSize >= 0);
    assert(Number.isSafeInteger(fee) && fee >= 0);
    lines.push(`${weight}|${sigops}|${virtualSize}|${rate}|${fee}`);
  }
  return Buffer.from(`${lines.join('\n')}\n`, 'ascii');
}

function sidecar(content) {
  return `${sha256(content)}  ${path.basename(fixturePath)}\n`;
}

const content = render();
switch (mode) {
  case '--write':
    fs.mkdirSync(path.dirname(fixturePath), {recursive: true});
    fs.writeFileSync(fixturePath, content);
    fs.writeFileSync(`${fixturePath}.sha256`, sidecar(content), 'ascii');
    break;
  case '--check':
    assert(fs.readFileSync(fixturePath).equals(content), 'fixture differs');
    assert.strictEqual(
      fs.readFileSync(`${fixturePath}.sha256`, 'ascii'),
      sidecar(content),
      'fixture sidecar differs'
    );
    break;
  case '--print':
    process.stdout.write(content);
    break;
  default:
    throw new Error(
      'usage: generate-hsd-fee-policy-vectors.js [--write|--check] [hsd-root]'
    );
}
